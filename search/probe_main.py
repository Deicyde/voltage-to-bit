#!/usr/bin/env python3
"""Compatibility probe. NOT part of the frozen experiment record.

    python3 search/probe_main.py

The experiment record is checked against the frozen commit of the library and
against nothing else. The library has moved on since then: on `main`,
`IsTrajectory` no longer takes a parameter point, and the theorems lost their
`θ` argument. This probe answers one practical question for whoever promotes
the accepted improvement: do the same two certificates, and the refined
guarantee restated in the current shape, check against the library as it is in
this working tree?

It takes the certificates from the record, writes
`search/promote/main/RefinedDeadlines.lean`, and checks it with

    cd "$R" && lake env lean "$R/search/promote/main/RefinedDeadlines.lean"

after verifying that the library sources in this working tree are committed
and that its build is up to date. The verdict, the commit it refers to and the
hashes are written to `search/promote/main/probe.json`.

A pass here says that the statements port to that commit. It does not extend
the frozen record, and it is not re-run by `run_search.py`.
"""
from __future__ import annotations

import datetime
import json
import subprocess
import sys
from fractions import Fraction
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from v2bsearch import leanio, record  # noqa: E402
from v2bsearch.exact import dec_str  # noqa: E402

REPO = Path(__file__).resolve().parents[1]
SEARCH = REPO / "search"
LIBRARY_PATHS = ["VoltageToBit", "VoltageToBit.lean", "lakefile.toml", "lake-manifest.json",
                 "lean-toolchain", "designs/illustrative-1v8.json"]
PROMOTE_N = 16

# The frozen-commit statement -> the statement in the current shape.
REWRITES = [
    ("theorem illustrative_guarantee_refined (θ : Params) (hθ : illustrative.InBox θ) (u v : ℝ → ℝ)",
     "theorem illustrative_guarantee_refined (u v : ℝ → ℝ)"),
    ("(h : IsTrajectory illustrative θ u v a b)", "(h : IsTrajectory illustrative u v a b)"),
    ("exact h.safe illustrative_admissible hθ h0' t ht", "exact h.safe illustrative_admissible h0' t ht"),
    ("h.rise_of_cert illustrative_admissible hθ h0'", "h.rise_of_cert illustrative_admissible h0'"),
    ("h.fall_of_cert illustrative_admissible hθ h0'", "h.fall_of_cert illustrative_admissible h0'"),
]


def git(*argv: str) -> str:
    return subprocess.run(["git", "-C", str(REPO), *argv], capture_output=True, text=True,
                          check=True).stdout.strip()


def main() -> int:
    records = record.read_jsonl(SEARCH / "records" / "records.jsonl")

    def pick(experiment: str) -> dict:
        for r in records:
            if (r["experiment_id"] == experiment and r["decision"] == "accepted"
                    and r["proposer"]["name"] == "dp-grid" and r["proposer"]["params"]["N"] == PROMOTE_N):
                return r
        raise SystemExit(f"no accepted {PROMOTE_N}-level certificate in {experiment}")

    rise, fall = pick("rise-deadline"), pick("fall-deadline")
    commit = git("rev-parse", "HEAD")
    dirty = git("status", "--porcelain", "--", *LIBRARY_PATHS)
    if dirty:
        raise SystemExit(f"library sources have uncommitted changes; probe not run:\n{dirty}")
    fresh = subprocess.run(["lake", "build", "--no-build", "VoltageToBit"], cwd=str(REPO),
                           capture_output=True, text=True)
    if fresh.returncode != 0:
        raise SystemExit("the working tree's build is not up to date; probe not run")

    strip = lambda t: dec_str(Fraction(t))
    body, names = leanio.promotion_file(
        rise["record_id"], rise["proposal"]["levels"], strip(rise["proposal"]["tau"]),
        fall["record_id"], fall["proposal"]["levels"], strip(fall["proposal"]["tau"]))
    for old, new in REWRITES:
        if old not in body:
            raise SystemExit(f"template changed; rewrite not applicable: {old!r}")
        body = body.replace(old, new)
    folder = SEARCH / "promote" / "main"
    lean = folder / "RefinedDeadlines.lean"
    header = {"RECORD": f"{rise['record_id']} + {fall['record_id']}",
              "EXPERIMENT": "compatibility probe, not part of the frozen record",
              "CONTEXT": "n/a", "COMMIT": commit + " (working tree `main`, not the frozen commit)",
              "DESIGNFILE": "designs/illustrative-1v8.json",
              "DESIGNSHA": rise["context"]["design_sha256"], "ROLE": "compatibility probe",
              "PROPOSER": "dp-grid",
              "ABOUT": "The accepted improvement restated for the current shape of the library "
                       "(`IsTrajectory` without a parameter point)."}
    leanio.write_lean(lean, header, body)
    text = lean.read_text(encoding="utf-8").replace(
        "GENERATED by search/run_search.py", "GENERATED by search/probe_main.py", 1)
    lean.write_text(text, encoding="utf-8")
    sha = record.sha256_text(text)
    res = leanio.run_lean(REPO, REPO, lean, folder / "RefinedDeadlines.out", names)
    res.pop("_seconds")
    res["command"] = f'cd "$R" && lake env lean "$R/{res["lean_file"]}"'
    probe = {
        "note": "Compatibility probe against the working tree of the library. Not part of the "
                "frozen experiment record.",
        "checked_against_commit": commit,
        "library_sources_committed": True,
        "build_up_to_date": True,
        "frozen_commit_of_the_record": rise["context"]["lean_commit"],
        "design_sha256_in_record": rise["context"]["design_sha256"],
        "design_sha256_in_working_tree": record.sha256_text(
            (REPO / "designs/illustrative-1v8.json").read_text(encoding="utf-8")),
        "rise_record": rise["record_id"], "fall_record": fall["record_id"],
        "rise_tau": strip(rise["proposal"]["tau"]), "fall_tau": strip(fall["proposal"]["tau"]),
        "lean_file_sha256": sha,
        **res,
        "probed_utc": datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
    }
    (folder / "probe.json").write_text(json.dumps(probe, indent=1, ensure_ascii=False) + "\n",
                                       encoding="utf-8")
    print(f"commit {commit}: exit status {res['exit_status']}, "
          f"{'PASSED' if res['passed'] else 'FAILED'}")
    for name in names:
        print(f"  {name}: axioms {res['axioms'][name]}")
    return 0 if res["passed"] else 1


if __name__ == "__main__":
    sys.exit(main())
