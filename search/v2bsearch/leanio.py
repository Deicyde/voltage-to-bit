"""Generation of Lean files and the formal check.

Each proposal gets one or more small, standalone Lean files that start with
``import VoltageToBit``. They are checked from the frozen checkout, so the
library they are checked against is exactly the frozen commit:

    cd "$FROZEN" && lake env lean "$R/search/lean/<file>.lean"

Roles of a generated file
-------------------------
claim           the proposal's claim, stated positively. Exit status 0 with no
                error and only the three standard axioms means Lean accepted it.
refutation      the negation of the claim (only attempted after Lean rejected
                the claim). Shows the proposal is false, not merely unproved.
counterexample  an explicit trajectory of the model that violates the claimed
                deadline (only for deadlines below the Lean-proved floor).

Lean is the arbiter. Nothing in this module decides anything by itself; it
writes files, runs the checker and reports what the checker printed.
"""
