# ------------------------------------------------------------- running Lean

# Nothing that could switch off or bypass checking may appear in a generated
# file. `#print axioms` does not reveal a declaration added with the kernel
# check disabled by an option (adversarial review, finding E1-08), so the
# generated text itself is scanned. The templates use none of these words, and
# proposers can only contribute plain decimals (`lit`).
FORBIDDEN = re.compile(
    r"\b(sorry|admit|native_decide|implemented_by|unsafe|set_option|run_cmd|run_elab|elab|"
    r"macro|macro_rules|syntax|notation|attribute|instance|opaque|axiom|extern|"
    r"skipKernelTC)\b")


def forbidden_tokens(text: str) -> list[str]:
    """Forbidden words in a Lean source, ignoring the generated header comment."""
    body = text.split("namespace VoltageToBit.Search", 1)[-1]
    return sorted(set(m.group(1) for m in FORBIDDEN.finditer(body)))


def write_lean(path: Path, header: dict, body: str) -> str:
    """Write a generated Lean file; returns its SHA-256."""
    text = fill(HEADER, **header) + body + FOOTER
    bad = forbidden_tokens(text)
    if bad:
        raise ValueError(f"generated file {path.name} would contain forbidden tokens {bad}")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


# Lean wraps the axiom list over several lines when the theorem name is long,
# so these are matched against the whole output, not line by line.
AXIOM_LINE = re.compile(r"'([^'\n]+)' depends on axioms: \[([^\]]*)\]")
NO_AXIOM_LINE = re.compile(r"'([^'\n]+)' does not depend on any axioms")


def run_lean(frozen: Path, repo: Path, lean_file: Path, out_file: Path,
             expected: list[str], timeout_s: int = 3600) -> dict:
    """Run the formal check on one generated file and report what Lean said.

    The captured output (stdout then stderr) is stored with the absolute
    repository path replaced by nothing, so that it does not depend on where
    the repository lives; its hash is the hash of the stored file.

    ``passed`` requires: exit status 0, no ``error`` message, and every
    expected theorem reported by ``#print axioms`` with axioms inside
    {propext, Classical.choice, Quot.sound} (so no `sorryAx`).
    """
    started = time.time()
    proc = subprocess.run(["lake", "env", "lean", str(lean_file)], cwd=str(frozen),
                          capture_output=True, text=True, timeout=timeout_s)
    seconds = time.time() - started
    raw = proc.stdout + proc.stderr
    text = raw.replace(str(repo) + "/", "").replace(str(frozen) + "/", "$FROZEN/")
    out_file.parent.mkdir(parents=True, exist_ok=True)
    out_file.write_text(text, encoding="utf-8")

    axioms: dict[str, list[str]] = {}
    for m in AXIOM_LINE.finditer(text):
        axioms[m.group(1).split(".")[-1]] = [a.strip() for a in m.group(2).split(",") if a.strip()]
    for m in NO_AXIOM_LINE.finditer(text):
        axioms[m.group(1).split(".")[-1]] = []
    messages = parse_messages(text)
    errors = [m for m in messages if m["severity"] == "error"]
    warnings = [m for m in messages if m["severity"] == "warning"]
    unsolved = [ln.split()[1] for m in errors if "unsolved goals" in m["lines"][0]
                for ln in m["lines"][1:] if ln.startswith("case ")]
    clean_axioms = all(name in axioms and set(axioms[name]) <= ALLOWED_AXIOMS for name in expected)
    passed = proc.returncode == 0 and not errors and clean_axioms
    rel = lambda p: str(p.relative_to(repo))
    return {
        "command": f'cd "$FROZEN" && lake env lean "$R/{rel(lean_file)}"',
        "lean_file": rel(lean_file),
        "exit_status": proc.returncode,
        "output_file": rel(out_file),
        "output_sha256": hashlib.sha256(text.encode("utf-8")).hexdigest(),
        "error_count": len(errors),
        "warning_count": len(warnings),
        "first_error": " | ".join(ln for ln in errors[0]["lines"] if ln.strip())[:400] if errors else None,
        "unsolved_cases": unsolved,
        "theorems": expected,
        "axioms": {name: axioms.get(name) for name in expected},
        "passed": passed,
        "_seconds": seconds,
    }


MESSAGE_START = re.compile(r"^\S+:\d+:\d+: (error|warning|info)\b")


def parse_messages(text: str) -> list[dict]:
    """Split Lean's output into diagnostic messages (severity + their lines)."""
    messages, current = [], None
    for line in text.splitlines():
        m = MESSAGE_START.match(line)
        if m:
            current = {"severity": m.group(1), "lines": [line]}
            messages.append(current)
        elif line.startswith("'") and "axioms" in line:
            current = None                      # output of `#print axioms`
        elif current is not None:
            current["lines"].append(line)
    return messages


