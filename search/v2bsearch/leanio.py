def axioms_block(names: list[str]) -> str:
    return "\n" + "\n".join(f"#print axioms {n}" for n in names) + "\n"


# ------------------------------------------------------- certificate: claim

CERT_CLAIM = """
/-- The proposed certificate is valid for the claimed deadline `@TAU@` ns. -/
theorem @NAME@ :
    illustrative.@Valid@ @HEAD@
      @TAIL@
      @TAU@ := by
  refine ⟨?_, ?_, ?_⟩ <;>
    norm_num [@Segs@, finalLevel, @time@, Design.@segs@, Design.@margin@, illustrative,
      psq_eq_ite]
"""

CERT_SUM = """
/-- Exact value of the certificate's summed segment times. The cheap screen
computed this fraction; Lean confirms it. -/
theorem @NAME@_sum :
    @time@ illustrative.@start@
        (illustrative.@segs@
          @FULL@) =
      @SUM@ := by
  norm_num [@time@, Design.@segs@, Design.@margin@, illustrative, psq_eq_ite]
"""

CERT_BASELINE = """
/-- The single-segment certificate is exactly the library's closed-form deadline. -/
theorem @NAME@_is_library_deadline :
    @time@ illustrative.@start@ (illustrative.@segs@ [@TARGETLIT@]) = illustrative.@libtau@ := by
  rw [@libthm@]
  norm_num [@time@, Design.@segs@, Design.@margin@, illustrative, psq_eq_ite]
"""


def cert_claim(direction: str, name: str, levels: list[str], tau: str,
               exact_sum: Fraction | None, baseline_target: str | None = None):
    """Lean text and theorem names for a certificate claim.

    ``exact_sum`` is given only when the screen found the certificate valid;
    then Lean is also asked to confirm the exact sum.
    """
    d = DIR[direction]
    common = dict(d, NAME=name, HEAD=lit(levels[0]), TAIL=lean_list(levels[1:], 6),
                  FULL=lean_list(levels, 10), TAU=lit(tau))
    body = fill(CERT_CLAIM, **common)
    names = [name]
    if exact_sum is not None:
        body += fill(CERT_SUM, SUM=frac_lit(exact_sum), **common)
        names.append(f"{name}_sum")
    if baseline_target is not None:
        body += fill(CERT_BASELINE, TARGETLIT=lit(baseline_target), **common)
        names.append(f"{name}_is_library_deadline")
    return body + axioms_block(names), names


# -------------------------------------------------- certificate: refutation

CERT_REFUTE = """
/-- The proposed certificate does **not** support the claimed deadline:
its `@WHICH@` condition is false. -/
theorem @NAME@_refuted :
    ¬ illustrative.@Valid@ @HEAD@
      @TAIL@
      @TAU@ := by
  rintro ⟨@PATTERN@⟩
  norm_num [@LEMMAS@] at h
"""


def cert_refutation(direction: str, name: str, levels: list[str], tau: str, first_failure: str):
    d = DIR[direction]
    if first_failure == "segments":
        pattern = "h, -, -"
        lemmas = f"{d['Segs']}, Design.{d['segs']}, Design.{d['margin']}, illustrative, psq_eq_ite"
    elif first_failure == "final_level":
        pattern = "-, h, -"
        lemmas = f"finalLevel, Design.{d['segs']}, illustrative"
    elif first_failure == "deadline":
        pattern = "-, -, h"
        lemmas = f"{d['time']}, Design.{d['segs']}, Design.{d['margin']}, illustrative, psq_eq_ite"
    else:
        raise ValueError(first_failure)
    body = fill(CERT_REFUTE, NAME=name, HEAD=lit(levels[0]), TAIL=lean_list(levels[1:], 6),
                TAU=lit(tau), PATTERN=pattern, LEMMAS=lemmas, WHICH=first_failure, **d)
    names = [f"{name}_refuted"]
    return body + axioms_block(names), names


