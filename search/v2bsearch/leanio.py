# ------------------------------------------------------------------ literals

def lit(text: str) -> str:
    """A decimal string as a Lean real literal (parenthesised when negative).

    Every number a proposer supplies reaches a Lean file through this function,
    and nothing but a plain decimal is let through: a proposer cannot put Lean
    source into a generated file.
    """
    if not exact.DECIMAL.match(text):
        raise ValueError(f"not a plain decimal: {text!r}")
    return f"({text})" if text.startswith("-") else text


def frac_lit(x: Fraction) -> str:
    """An exact rational as a Lean term."""
    if x.denominator == 1:
        return lit(str(x.numerator))
    body = f"{abs(x.numerator)} / {x.denominator}"
    return f"(-({body}))" if x < 0 else body


def lean_list(items: list[str], indent: int, width: int = 96) -> str:
    """`[a, b, ...]` wrapped over several lines."""
    text = "[" + ", ".join(lit(i) for i in items) + "]"
    lines = textwrap.wrap(text, width=width - indent, break_long_words=False)
    return ("\n" + " " * indent).join(lines)


def lean_name(record_id: str) -> str:
    return re.sub(r"[^A-Za-z0-9_]", "_", record_id)


def fill(template: str, **values: str) -> str:
    out = template
    for key, value in values.items():
        out = out.replace(f"@{key}@", value)
    left = re.findall(r"@[A-Za-z0-9_]+@", out)
    if left:
        raise KeyError(f"unfilled template keys: {sorted(set(left))}")
    return out


