ADM_DEF = """
/-- The variant record: only `eps` and the proof-only split points `uHi`, `uLo`
differ from `illustrative`; every circuit and environment number is inherited. -/
noncomputable def @NAME@_design : Design :=
  { illustrative with eps := @EPS@, uHi := @UHI@, uLo := @ULO@ }
"""

ADM_CLAIM = """
/-- The variant record satisfies every numeric admissibility condition. -/
theorem @NAME@ : @NAME@_design.Admissible := by
  constructor <;>
    norm_num [@NAME@_design, illustrative, Design.Iup, Design.Idn, Design.RhiP, Design.RhiN,
      Design.RloN, Design.RloP, psq_eq_ite]
"""

ADM_TAUS = """
/-- Side effect of a different disturbance bound: the variant's own closed-form
rise deadline. -/
theorem @NAME@_tauUp : @NAME@_design.tauUp = @TAUUP@ := by
  norm_num [@NAME@_design, illustrative, Design.tauUp, Design.Iup, psq_eq_ite]

/-- ... and its own closed-form fall deadline. -/
theorem @NAME@_tauDn : @NAME@_design.tauDn = @TAUDN@ := by
  norm_num [@NAME@_design, illustrative, Design.tauDn, Design.Idn, psq_eq_ite]
"""

ADM_REFUTE = """
/-- The variant record is **not** admissible: its `@FIELD@` condition is false. -/
theorem @NAME@_refuted : ¬ @NAME@_design.Admissible := fun h => by
  have h1 := h.@FIELD@
  norm_num [@LEMMAS@] at h1
"""

ADM_CEILING = """
/-- **No choice of the split points helps.** Once `eps ≥ @E@`, the record is
inadmissible for every `uHi` and `uLo`: for `uHi ≤ @X0@` the NMOS-branch margin
`RhiN` is too small, and for `uHi ≥ @X0@` the PMOS-branch margin `RhiP` is. -/
theorem @NAME@_no_split_points (e x y : ℝ) (he : @E@ ≤ e) :
    ¬ ({ illustrative with eps := e, uHi := x, uLo := y } : Design).Admissible := by
  intro h
  have hP := h.hiP
  have hN := h.hiN
  simp only [Design.RhiP, Design.RhiN, illustrative] at hP hN
  rcases le_total x @X0@ with hx | hx
  · have h1 : psq (x - @Vtnhi@) ≤ psq (@X0@ - @Vtnhi@) := psq_mono (by linarith)
    have h2 := psq_nonneg (x - @Vhi@ - @Vtnhi@)
    have h3 : psq (@X0@ - @Vtnhi@ : ℝ) = @A@ := by norm_num [psq_eq_ite]
    rw [h3] at h1
    linarith
  · have h1 := psq_incr_mono (d := (@Vhi@ - @VDDhi@ : ℝ)) (x := @VDDlo@ - x - @Vtphi@)
      (y := @VDDlo@ - @X0@ - @Vtphi@) (by norm_num) (by linarith)
    have h3 : psq (@VDDlo@ - @X0@ - @Vtphi@ + (@Vhi@ - @VDDhi@) : ℝ)
        - psq (@VDDlo@ - @X0@ - @Vtphi@) = @B@ := by
      norm_num [psq_eq_ite]
    rw [h3] at h1
    linarith
"""

FIELD_LEMMAS = {"up": "Design.Iup", "dn": "Design.Idn", "hiP": "Design.RhiP",
                "hiN": "Design.RhiN", "loN": "Design.RloN", "loP": "Design.RloP"}


def adm_claim(name: str, eps: str, uHi: str, uLo: str, taus: tuple[Fraction, Fraction] | None):
    common = dict(NAME=name, EPS=lit(eps), UHI=lit(uHi), ULO=lit(uLo))
    body = fill(ADM_DEF, **common) + fill(ADM_CLAIM, **common)
    names = [name]
    if taus is not None:
        body += fill(ADM_TAUS, TAUUP=frac_lit(taus[0]), TAUDN=frac_lit(taus[1]), **common)
        names += [f"{name}_tauUp", f"{name}_tauDn"]
    return body + axioms_block(names), names


def ceiling_constants(D: Design, E: Fraction, x0: Fraction) -> dict | None:
    """Constants for `ADM_CEILING`, or None when `x0` does not witness the
    ceiling `E` (both upper-boundary margins at `x0` must be <= E)."""
    half = Fraction(1, 2)
    a = exact.psq(x0 - D.Vtnhi)
    y0 = D.VDDlo - x0 - D.Vtphi
    b = exact.psq(y0 + (D.Vhi - D.VDDhi)) - exact.psq(y0)
    if not (D.knlo * half * a <= E and D.kplo * half * b <= E and D.Vhi >= D.VDDhi):
        return None
    return {"E": exact.dec_str(E), "X0": exact.dec_str(x0), "A": exact.dec_str(a),
            "B": exact.dec_str(b)}


def adm_refutation(D: Design, name: str, eps: str, uHi: str, uLo: str, field: str,
                   ceiling: dict | None):
    common = dict(NAME=name, EPS=lit(eps), UHI=lit(uHi), ULO=lit(uLo))
    lemmas = f"{name}_design, illustrative"
    if field in FIELD_LEMMAS:
        lemmas += f", {FIELD_LEMMAS[field]}, psq_eq_ite"
    body = fill(ADM_DEF, **common) + fill(ADM_REFUTE, FIELD=field, LEMMAS=lemmas, **common)
    names = [f"{name}_refuted"]
    if ceiling is not None:
        raw = {k: D.raw[k] for k in ("Vtnhi", "Vhi", "VDDhi", "VDDlo", "Vtphi")}
        body += fill(ADM_CEILING, NAME=name, **ceiling, **raw)
        names.append(f"{name}_no_split_points")
    return body + axioms_block(names), names


