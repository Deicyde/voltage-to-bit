COMMON_OPTS = ".options TEMP=27 TNOM=27 RELTOL=1e-6"


def _level1_models(th) -> str:
    VDD, kn, kp, Vtn, Vtp = th
    return (
        "* Level 1 (Shichman-Hodges), LAMBDA=0, GAMMA=0, W=L so that beta = KP.  k [uA/V^2] -> KP [A/V^2].\n"
        "* TOX, CGSO, CGDO, CGBO, CBD, CBS, CJ are deliberately NOT given: the formal model has no device\n"
        "* capacitance.  VERIFY ON FIRST RUN that `show` reports zero cgs/cgd/cbd/cbs (Meyer capacitances are\n"
        "* believed to be disabled when TOX is absent; this has not been checked against this ngspice build).\n"
        "* IS=1e-30 (as proposed in docs/model.md 9.4): with the default IS=1e-14 A the PMOS drain junction\n"
        "* would carry about 0.5 uA at v = V_hi when VDD = VDD_min (0.46 V forward bias) and spoil the identity\n"
        "* check there. GMIN stays at its default 1e-12 S (about 2e-6 uA across 2 V), the expected residual floor.\n"
        f".model NFORMAL NMOS (LEVEL=1 VTO={Vtn:.6g} KP={kn:.6g}u LAMBDA=0 GAMMA=0 PHI=0.6 IS=1e-30)\n"
        f".model PFORMAL PMOS (LEVEL=1 VTO=-{Vtp:.6g} KP={kp:.6g}u LAMBDA=0 GAMMA=0 PHI=0.6 IS=1e-30)"
    )


def level1_dc(D: Design, code: str, th, v_step: float = 0.02, u_step: float = 0.05) -> str:
    F = float_design(D)
    VDD = th[0]
    tag = f"level1_dc_{code}"
    return "\n".join([
        f"* (a) [tier T1] Level-1 DC map of I_net(u, v) at corner {code}: " + ", ".join(f"{k}={x:g}" for k, x in zip(THETA_KEYS, th)),
        BANNER.format(name=D.name, sha=D.sha256),
        "* Compared with: Python I_net(u, v; theta) at the same grid points (expected agreement ~1e-5 uA).",
        "* Sign: I_net into the output node = +i(VOUT) (current from the + node through the source to ground).",
        COMMON_OPTS,
        _level1_models(th),
        f"VDD vdd 0 DC {VDD:.6g}",
        "VIN in 0 DC 0",
        "VOUT out 0 DC 0",
        "MP out in vdd vdd PFORMAL W=1u L=1u",
        "MN out in 0 0 NFORMAL W=1u L=1u",
        ".control",
        "set wr_singlescale",
        "set wr_vecnames",
        "set numdgt=12",
        f"dc VOUT {F.Vlo:.6g} {F.Vhi:.6g} {v_step:g} VIN {F.Vlo - 0.4:.6g} {F.Vhi + 0.4:.6g} {u_step:g}",
        f"wrdata {tag}.dat i(VOUT) v(in)",
        "show MN : cgs cgd cbd cbs",
        "show MP : cgs cgd cbd cbs",
        ".endc",
        ".end",
        "",
    ])


def _tran_sources(F, pol: str, slew: float, w_uA: float) -> tuple[list[str], float, float]:
    """Input ramp from the opposite rail to the band edge (reached at t = s) and a constant disturbance source."""
    hold = 0.05
    if pol == "L":
        start, edge = F.VDD_hi, F.VIL
    else:
        start, edge = 0.0, F.VIH
    s = hold + abs(start - edge) / slew
    lines = [
        f"VIN in 0 PWL(0 {start:.6g} {hold:.6g}n {start:.6g} {s:.9g}n {edge:.6g})",
        f"* disturbance: {w_uA:+g} uA INTO the output node (I n+ n-: current flows n+ -> source -> n-)",
        f"IW 0 out DC {w_uA:.6g}u",
    ]
    return lines, s, edge


def level1_tran(D: Design, code: str, th, pol: str, slew: float = 2.0) -> str:
    F = float_design(D)
    VDD = th[0]
    tau = float(tau_up(D) if pol == "L" else tau_dn(D))
    w = -F.eps if pol == "L" else F.eps
    v0 = F.Vlo if pol == "L" else F.Vhi
    thr = F.VOH if pol == "L" else F.VOL
    src, s, edge = _tran_sources(F, pol, slew, w)
    t_end = s + 1.25 * tau + 0.5
    tag = f"level1_tran_{'rise' if pol == 'L' else 'fall'}_{code}"
    return "\n".join([
        f"* (a) [tier T1] Level-1 transient, output {'rise' if pol == 'L' else 'fall'} at corner {code}, C = C_max, worst-case constant disturbance",
        BANNER.format(name=D.name, sha=D.sha256),
        f"* Input reaches the valid-band edge ({edge:g} V) at s = {s:.6g} ns; output threshold {thr:g} V; formal bound tau = {tau:.9g} ns.",
        "* Compared with: Python simulation of the same theta, C, u(t), w(t), v(0): crossing time of the output",
        "* threshold after s, and the sampled waveform (expected agreement at the level of the SPICE tolerances).",
        COMMON_OPTS,
        _level1_models(th),
        f"VDD vdd 0 DC {VDD:.6g}",
        *src,
        f"CL out 0 {F.C_hi:.6g}f IC={v0:.6g}",
        "MP out in vdd vdd PFORMAL W=1u L=1u",
        "MN out in 0 0 NFORMAL W=1u L=1u",
        f".ic v(out)={v0:.6g}",
        ".control",
        "set wr_singlescale",
        "set wr_vecnames",
        "set numdgt=12",
        f"tran 1p {t_end:.6g}n 0 1p uic",
        f"wrdata {tag}.dat v(out) v(in)",
        ".endc",
        ".end",
        "",
    ])


