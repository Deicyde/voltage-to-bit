def write_decks(D: Design, outdir, worst_codes: dict) -> list[str]:
    """Render the example decks. Returns the list of file names written."""
    F = float_design(D)
    outdir.mkdir(parents=True, exist_ok=True)
    nominal = [0.5 * (F.lo(k) + F.hi(k)) for k in THETA_KEYS]
    files = {}
    files["level1_dc_nominal.cir"] = level1_dc(D, "nominal", nominal)
    for pol in ("L", "H"):
        code = worst_codes[pol]
        th = [float(x) for x in corner_by_code(D, code)]
        files[f"level1_dc_{code}.cir"] = level1_dc(D, code, th)
        files[f"level1_tran_{'rise' if pol == 'L' else 'fall'}_{code}.cir"] = level1_tran(D, code, th, pol)
    files["sky130_T3_dc_tt_1v8_27C.cir"] = sky130_dc(D, 1.8)
    files["sky130_T3_tran_rise_tt_1v8_27C.cir"] = sky130_tran(D, 1.8, "L", F.C_lo)
    files["sky130_T3_tran_fall_tt_1v8_27C.cir"] = sky130_tran(D, 1.8, "H", F.C_lo)
    for stale in outdir.glob("*.cir"):
        if stale.name not in files:
            stale.unlink()
    for name, text in files.items():
        (outdir / name).write_text(text)
    return sorted(files)
