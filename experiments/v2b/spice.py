        f".options TEMP={temp:g}",
        f'.lib "SKY130_PR_PLACEHOLDER/models/sky130.lib.spice" {corner}',
        f"VDD vdd 0 DC {vdd:.6g}",
        "VIN in 0 DC 0",
        "VOUT out 0 DC 0",
        f"XMP out in vdd vdd sky130_fd_pr__pfet_01v8_hvt L={l:g} W={wp:g} nf=1 mult=1",
        f"XMN out in 0 0 sky130_fd_pr__nfet_01v8 L={l:g} W={wn:g} nf=1 mult=1",
        ".control",
        "set ngbehavior=hsa",
        "set skywaterpdk",
