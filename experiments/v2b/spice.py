        "set numdgt=12",
        f"dc VOUT {F.Vlo:.6g} {F.Vhi:.6g} 0.02 VIN {F.Vlo:.6g} {F.Vhi:.6g} 0.02",
        f"wrdata {tag}.dat i(VOUT) v(in)",
        ".endc",
        ".end",
